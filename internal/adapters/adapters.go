// Package adapters turns the policy and the vendored rules into each coding agent's native instruction
// files, and keeps them in sync.
//
//	claude   CLAUDE.md                     managed block: @-imports the core rules, lists the rest
//	codex    AGENTS.md                     managed block: core rules inline, the rest by path
//	copilot  .github/copilot-instructions.md (core) + .github/instructions/intellisense-*.instructions.md
//	cursor   .cursor/rules/intellisense-*.mdc
//
// "Core" is workflow.md plus the baseline rules: always in context. Every other rule is scoped to the files
// it applies to where the agent supports that (Copilot applyTo, Cursor globs) and listed by path where it
// does not. Files intellisense owns carry a "Generated by intellisense" line; in CLAUDE.md and AGENTS.md it
// owns only the block between the markers, so your own text there is kept.
package adapters

import (
	"fmt"
	"strings"

	"github.com/soupler-oss/intellisense/internal/policy"
	"github.com/soupler-oss/intellisense/internal/rules"
)

// Markers around the block intellisense owns in a shared file.
const (
	BeginMarker = "<!-- intellisense:begin -->"
	EndMarker   = "<!-- intellisense:end -->"
)

// GeneratedLine marks a file intellisense owns completely.
const GeneratedLine = "<!-- Generated by intellisense sync from .intellisense.yml and .intellisense/rules/. Do not edit: change those and run `intellisense sync`. -->"

// Output is one file intellisense writes.
type Output struct {
	// Path is repo-relative with / separators.
	Path string
	// Content is the whole file, or only the managed block when Block is set.
	Content string
	// Block means Path is shared: only the text between the markers is intellisense's.
	Block bool
	// Agent that owns the output ("" for the workflow rule every agent shares).
	Agent string
}

// Owned file-name patterns, used to find outputs that a policy no longer asks for.
const (
	CopilotDir    = ".github/instructions/"
	CopilotPrefix = "intellisense-"
	CopilotSuffix = ".instructions.md"
	CursorDir     = ".cursor/rules/"
	CursorPrefix  = "intellisense-"
	CursorSuffix  = ".mdc"
	CopilotCore   = ".github/copilot-instructions.md"
)

// Generate computes every output for the policy and rules.
func Generate(p *policy.Policy, rs []rules.Rule) []Output {
	if len(p.Agents) == 0 {
		return nil // nothing reads the workflow rule without an agent
	}
	workflow := Workflow(p)
	out := []Output{{Path: rules.WorkflowFile, Content: "---\nload_when: always\n---\n\n" + GeneratedLine + "\n\n" + workflow}}
	var core, scoped []rules.Rule
	for _, r := range rs {
		if r.Kind == rules.KindBaseline {
			core = append(core, r)
		} else {
			scoped = append(scoped, r)
		}
	}
	if p.HasAgent("claude") {
		out = append(out, Output{Path: "CLAUDE.md", Block: true, Agent: "claude", Content: claude(core, scoped)})
	}
	if p.HasAgent("codex") {
		out = append(out, Output{Path: "AGENTS.md", Block: true, Agent: "codex", Content: codex(workflow, core, scoped)})
	}
	if p.HasAgent("copilot") {
		out = append(out, copilot(workflow, core, scoped)...)
	}
	if p.HasAgent("cursor") {
		out = append(out, cursor(workflow, core, scoped)...)
	}
	return out
}

const intro = "This repository is governed by [intellisense](https://github.com/soupler-oss/intellisense): " +
	"every change has a risk tier, and the pre-push hook and CI block one that lacks the evidence its tier needs."

func claude(core, scoped []rules.Rule) string {
	var b strings.Builder
	b.WriteString("## Governance (intellisense)\n\n" + intro + "\n\n")
	b.WriteString("@" + rules.WorkflowFile + "\n")
	for _, r := range core {
		b.WriteString("@" + r.Path + "\n")
	}
	writeOnDemand(&b, scoped)
	return b.String()
}

func codex(workflow string, core, scoped []rules.Rule) string {
	var b strings.Builder
	b.WriteString("## Governance (intellisense)\n\n" + intro + "\n\n")
	b.WriteString(demote(workflow))
	for _, r := range core {
		b.WriteString("\n" + demote(r.Body))
	}
	writeOnDemand(&b, scoped)
	return b.String()
}

// writeOnDemand lists the scoped rules for agents that read files when told to.
func writeOnDemand(b *strings.Builder, scoped []rules.Rule) {
	if len(scoped) == 0 {
		return
	}
	b.WriteString("\n### Read before you work on matching files\n\n")
	for _, r := range scoped {
		scope := "all files"
		if len(r.Globs) > 0 {
			scope = "`" + strings.Join(r.Globs, "`, `") + "`"
		}
		fmt.Fprintf(b, "- `%s` — %s (%s)\n", r.Path, r.Title, scope)
	}
}

func copilot(workflow string, core, scoped []rules.Rule) []Output {
	var b strings.Builder
	b.WriteString(GeneratedLine + "\n\n# Repository instructions\n\n" + intro + "\n\n" + demote(workflow))
	for _, r := range core {
		b.WriteString("\n" + demote(r.Body))
	}
	out := []Output{{Path: CopilotCore, Agent: "copilot", Content: b.String()}}
	for _, r := range scoped {
		apply := "**"
		if len(r.Globs) > 0 {
			apply = strings.Join(r.Globs, ",")
		}
		out = append(out, Output{
			Path:    CopilotDir + CopilotPrefix + r.Slug() + CopilotSuffix,
			Agent:   "copilot",
			Content: fmt.Sprintf("---\napplyTo: %q\n---\n\n%s\n\n%s", apply, GeneratedLine, r.Body),
		})
	}
	return out
}

func cursor(workflow string, core, scoped []rules.Rule) []Output {
	var b strings.Builder
	b.WriteString("---\ndescription: Change workflow, risk tiers and baseline rules for this repository\nalwaysApply: true\n---\n\n")
	b.WriteString(GeneratedLine + "\n\n" + intro + "\n\n" + workflow)
	for _, r := range core {
		b.WriteString("\n" + r.Body)
	}
	out := []Output{{Path: CursorDir + CursorPrefix + "core" + CursorSuffix, Agent: "cursor", Content: b.String()}}
	for _, r := range scoped {
		front := fmt.Sprintf("---\ndescription: %q\nalwaysApply: false\n---\n", r.Title)
		if len(r.Globs) > 0 {
			front = fmt.Sprintf("---\ndescription: %q\nglobs: %s\nalwaysApply: false\n---\n", r.Title, strings.Join(r.Globs, ","))
		}
		out = append(out, Output{
			Path:    CursorDir + CursorPrefix + r.Slug() + CursorSuffix,
			Agent:   "cursor",
			Content: front + "\n" + GeneratedLine + "\n\n" + r.Body,
		})
	}
	return out
}

// demote pushes every Markdown heading down two levels so inlined rules nest under the block's "##" heading.
// Fenced code is left alone.
func demote(md string) string {
	lines := strings.Split(md, "\n")
	fenced := false
	for i, l := range lines {
		if strings.HasPrefix(strings.TrimSpace(l), "```") {
			fenced = !fenced
			continue
		}
		if !fenced && strings.HasPrefix(l, "#") {
			hashes := len(l) - len(strings.TrimLeft(l, "#"))
			if hashes <= 4 && strings.HasPrefix(l[hashes:], " ") {
				lines[i] = "##" + l
			}
		}
	}
	return strings.Join(lines, "\n")
}
