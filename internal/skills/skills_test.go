package skills

import (
	"strings"
	"testing"
)

// A skill checked out with CRLF line endings (Windows) must still keep its front matter first.
func TestMarkGeneratedCRLF(t *testing.T) {
	got := markGenerated("---\r\nname: plan\r\ndescription: Plan first\r\n---\r\n\r\n# Plan\r\n")
	if !strings.HasPrefix(got, "---\nname: plan\n") {
		t.Fatalf("front matter should stay first:\n%s", got)
	}
	if !strings.Contains(got, "Generated by intellisense sync") {
		t.Fatalf("generated line missing:\n%s", got)
	}
}

func TestDescriptionCRLF(t *testing.T) {
	if got := description("---\r\nname: plan\r\ndescription: Plan first\r\n---\r\n"); got != "Plan first" {
		t.Fatalf("description = %q", got)
	}
}
