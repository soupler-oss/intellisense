func TestRulesUpdateKeepsEditsAndHonoursDisable(t *testing.T) {
	e := newEnv(t)
	if code, out := e.run("init", "--yes", "--no-hook"); code != ExitOK {
		t.Fatal(out)
	}
	testRule := filepath.Join(e.app, ".intellisense/rules/operational/testing.md")
	if err := os.WriteFile(testRule, []byte("# Testing\n\nOur own testing rule.\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	style := filepath.Join(e.app, ".intellisense/rules/operational/coding-style.md")
	if err := os.Remove(style); err != nil {
		t.Fatal(err)
	}
	code, out := e.in("rules", "update")
	if code != ExitOK || !strings.Contains(out, "kept      .intellisense/rules/operational/testing.md") || !strings.Contains(out, "updated   .intellisense/rules/operational/coding-style.md") {
		t.Fatalf("rules update: %d\n%s", code, out)
	}
	if !strings.Contains(readFile(t, testRule), "Our own testing rule.") {
		t.Fatal("an edited rule must survive rules update")
	}
	path := filepath.Join(e.app, ".intellisense.yml")
	if err := os.WriteFile(path, []byte(strings.Replace(readFile(t, path), "  disable: []", "  disable: ['operational/proof-standards']", 1)), 0o644); err != nil {
		t.Fatal(err)
	}
	if code, out := e.in("rules", "update"); code != ExitOK || !strings.Contains(out, "removed   .intellisense/rules/operational/proof-standards.md") {
		t.Fatalf("disabling an unedited rule removes it: %d\n%s", code, out)
	}
	if strings.Contains(readFile(t, filepath.Join(e.app, "AGENTS.md")), "proof-standards") {
		t.Error("a disabled rule must not reach the agents")
	}
}

