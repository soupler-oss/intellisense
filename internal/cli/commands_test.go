func TestInitYesWritesPolicyAndTrackerTrailers(t *testing.T) {
	e := newEnv(t)
	code, out := e.run("init", "--yes", "--no-hook", "--tracker", "jira", "--skills", "plan,tdd")
	if code != ExitOK || !strings.Contains(out, "Next:") {
		t.Fatalf("init: %d\n%s", code, out)
	}
	policyText := readFile(t, filepath.Join(e.app, ".intellisense.yml"))
	for _, want := range []string{"version: 1", "tracker: jira", "task_trailers: ['Jira', 'Task', 'Refs']", "skills: ['plan', 'tdd']"} {
		if !strings.Contains(policyText, want) {
			t.Errorf("policy should contain %q", want)
		}
	}
	skill := readFile(t, filepath.Join(e.app, ".claude/skills/plan/SKILL.md"))
	if !strings.HasPrefix(skill, "---\nname: plan\n") || !strings.Contains(skill, "Generated by intellisense sync") {
		t.Errorf("plan skill should keep its front matter first and be marked generated:\n%.200s", skill)
	}
	// Dropping a skill removes its generated files.
	path := filepath.Join(e.app, ".intellisense.yml")
	if err := os.WriteFile(path, []byte(strings.Replace(policyText, "skills: ['plan', 'tdd']", "skills: ['plan']", 1)), 0o644); err != nil {
		t.Fatal(err)
	}
	if code, out := e.run("sync"); code != ExitOK || !strings.Contains(out, "removed") {
		t.Fatalf("sync: %d\n%s", code, out)
	}
	if _, err := os.Stat(filepath.Join(e.app, ".claude/skills/tdd/SKILL.md")); err == nil {
		t.Error("tdd skill should be removed")
	}
	if code, out := e.run("init", "--yes", "--skills", "learn"); code != ExitError || !strings.Contains(out, "already exists") {
		t.Fatalf("second init must refuse: %d\n%s", code, out)
	}
}

func TestContractCommands(t *testing.T) {
	e := newEnv(t)
	if code, out := e.run("init", "--yes", "--no-hook"); code != ExitOK {
		t.Fatal(out)
	}
	code, out := e.in("contract", "new", "refund API")
	if code != ExitOK || !strings.Contains(out, "-refund-api.md") {
		t.Fatalf("contract new: %d\n%s", code, out)
	}
	matches, _ := filepath.Glob(filepath.Join(e.app, ".intellisense/contracts/*-refund-api.md"))
	if len(matches) != 1 {
		t.Fatalf("contract file not written: %v", matches)
	}
	if code, out := e.in("contract", "check", matches[0]); code != ExitBlocked || !strings.Contains(out, "scope is required") {
		t.Fatalf("an unfilled template must fail: %d\n%s", code, out)
	}
	body := readFile(t, matches[0])
	body = strings.Replace(body, "scope: '<scope>'", "scope: refund endpoint", 1)
	body = strings.Replace(body, "risk: '<risk>'", "risk: high", 1)
	if err := os.WriteFile(matches[0], []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}
	if code, out := e.in("contract", "check", matches[0]); code != ExitOK {
		t.Fatalf("a filled contract passes: %d\n%s", code, out)
	}
	if code, out := e.in("contract", "fields"); code != ExitOK || !strings.Contains(out, "risk (required): one of low, medium, high") {
		t.Fatalf("contract fields: %d\n%s", code, out)
	}
}

