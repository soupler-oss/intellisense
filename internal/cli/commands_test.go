// in runs a command with --dir first, so positional arguments can follow.
func (e *env) in(args ...string) (int, string) {
	e.t.Helper()
	var out bytes.Buffer
	full := append([]string{args[0], "--dir", e.app}, args[1:]...)
	if len(args) > 1 && !strings.HasPrefix(args[1], "-") {
		full = append([]string{args[0], args[1], "--dir", e.app}, args[2:]...)
	}
	code := Run(full, strings.NewReader(""), &out, &out)
	return code, out.String()
}

