func TestLiveTemplatesKeepEditsAndRefreshTheRest(t *testing.T) {
	e := newEnv(t)
	platform := t.TempDir()
	t.Setenv("INTELLISENSE_SETUP_PATH", platform)
	writeAt := func(root, rel, body string) {
		t.Helper()
		p := filepath.Join(root, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	// The platform's current templates.
	writeAt(platform, "templates/ci/refresh-docs.yml", "refresh v2\n")
	writeAt(platform, "templates/ci/intellisense-trailer-check.yml", "trailers v2\n")
	writeAt(platform, "scripts/validate-intellisense-trailers-pr.sh", "validator v2\n")
	// The repository: one file as installed (v1, recorded), one edited by the team, one missing.
	writeAt(e.app, ".github/workflows/refresh-docs.yml", "refresh v1\n")
	writeAt(e.app, ".github/workflows/intellisense-trailer-check.yml", "trailers v1 + our tweak\n")
	record := `{
  ".github/workflows/refresh-docs.yml": {"source": "templates/ci/refresh-docs.yml", "sha256": "` + sha([]byte("refresh v1\n")) + `"},
  ".github/workflows/intellisense-trailer-check.yml": {"source": "templates/ci/intellisense-trailer-check.yml", "sha256": "` + sha([]byte("trailers v1\n")) + `"},
  ".intellisense/scripts/validate-intellisense-trailers-pr.sh": {"source": "scripts/validate-intellisense-trailers-pr.sh", "sha256": "` + sha([]byte("validator v1\n")) + `"}
}`
	writeAt(e.app, TemplateRecord, record)

	code, out := e.in("live", "templates", "check")
	if code != ExitBlocked || !strings.Contains(out, "outdated  .github/workflows/refresh-docs.yml") ||
		!strings.Contains(out, "kept      .github/workflows/intellisense-trailer-check.yml (edited here") ||
		!strings.Contains(out, "missing   .intellisense/scripts/validate-intellisense-trailers-pr.sh") {
		t.Fatalf("check: %d\n%s", code, out)
	}
	if code, out := e.in("live", "templates", "update"); code != ExitOK {
		t.Fatalf("update: %d\n%s", code, out)
	}
	if got := readFile(t, filepath.Join(e.app, ".github/workflows/refresh-docs.yml")); got != "refresh v2\n" {
		t.Errorf("unedited file not refreshed: %q", got)
	}
	if got := readFile(t, filepath.Join(e.app, ".github/workflows/intellisense-trailer-check.yml")); !strings.Contains(got, "our tweak") {
		t.Errorf("edited file overwritten without --force: %q", got)
	}
	if got := readFile(t, filepath.Join(e.app, ".intellisense/scripts/validate-intellisense-trailers-pr.sh")); got != "validator v2\n" {
		t.Errorf("missing file not restored: %q", got)
	}
	if code, out := e.in("live", "templates", "update", "--force"); code != ExitOK {
		t.Fatalf("update --force: %d\n%s", code, out)
	}
	if got := readFile(t, filepath.Join(e.app, ".github/workflows/intellisense-trailer-check.yml")); got != "trailers v2\n" {
		t.Errorf("--force did not replace the edited file: %q", got)
	}
	baks, _ := filepath.Glob(filepath.Join(e.app, ".github/workflows/intellisense-trailer-check.yml.bak-*"))
	if len(baks) != 1 {
		t.Errorf("--force should keep one backup, found %v", baks)
	}
	if code, out := e.in("live", "templates", "check"); code != ExitOK || !strings.Contains(out, "are current") {
		t.Fatalf("check after update: %d\n%s", code, out)
	}
}
