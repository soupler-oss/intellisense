// A hook that already calls the gate (repo-governance's .githooks/pre-push) counts as installed.
func TestHookThatAlreadyRunsTheGate(t *testing.T) {
	e := newEnv(t)
	hooks := filepath.Join(e.app, ".git", "hooks")
	if err := os.WriteFile(filepath.Join(hooks, "pre-push"), []byte("#!/bin/sh\nexec intellisense gate --pre-push \"$@\"\n"), 0o755); err != nil {
		t.Fatal(err)
	}
	if code, out := e.run("hook", "install"); code != ExitOK || !strings.Contains(out, "already runs the gate") {
		t.Fatalf("hook install: %d\n%s", code, out)
	}
	if code, out := e.run("hook", "status"); code != ExitOK {
		t.Fatalf("hook status: %d\n%s", code, out)
	}
	if code, _ := e.run("hook", "uninstall"); code == ExitOK {
		t.Fatal("uninstall must not remove a hook intellisense did not write")
	}
}

