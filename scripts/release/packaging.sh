#!/usr/bin/env bash
# packaging.sh VERSION DIST_DIR — write the Homebrew formula and the Scoop manifest for a release.
#
# Reads DIST_DIR/checksums.txt (written by the release workflow) and writes:
#   DIST_DIR/intellisense.rb    Homebrew formula   → soupler-oss/homebrew-tap Formula/intellisense.rb
#   DIST_DIR/intellisense.json  Scoop manifest     → soupler-oss/scoop-bucket bucket/intellisense.json
#   DIST_DIR/winget/*.yaml      winget manifests   → a pull request to microsoft/winget-pkgs
#                                                    (manifests/s/Soupler/Intellisense/<version>/)
# so `brew install soupler-oss/tap/intellisense`, `scoop install intellisense` and
# `winget install Soupler.Intellisense` get this release.
set -euo pipefail

version="${1:?usage: packaging.sh VERSION DIST_DIR}"
version="${version#v}"
dist="${2:?usage: packaging.sh VERSION DIST_DIR}"
sums="$dist/checksums.txt"
[ -f "$sums" ] || { echo "no $sums" >&2; exit 1; }

sha() {
  local file="intellisense_${version}_$1"
  local s
  s="$(grep " $file\$" "$sums" | cut -d' ' -f1)"
  [ -n "$s" ] || { echo "$file is not in $sums" >&2; exit 1; }
  printf '%s' "$s"
}
url="https://github.com/soupler-oss/intellisense/releases/download/v$version"

cat > "$dist/intellisense.rb" <<RUBY
# Generated by scripts/release/packaging.sh for intellisense $version. Do not edit by hand.
class Intellisense < Formula
  desc "Risk tiers and evidence gates for AI-assisted development"
  homepage "https://github.com/soupler-oss/intellisense"
  version "$version"
  license "Apache-2.0"

  on_macos do
    on_arm do
      url "$url/intellisense_${version}_darwin_arm64.tar.gz"
      sha256 "$(sha darwin_arm64.tar.gz)"
    end
    on_intel do
      url "$url/intellisense_${version}_darwin_amd64.tar.gz"
      sha256 "$(sha darwin_amd64.tar.gz)"
    end
  end

  on_linux do
    on_arm do
      url "$url/intellisense_${version}_linux_arm64.tar.gz"
      sha256 "$(sha linux_arm64.tar.gz)"
    end
    on_intel do
      url "$url/intellisense_${version}_linux_amd64.tar.gz"
      sha256 "$(sha linux_amd64.tar.gz)"
    end
  end

  def install
    bin.install "intellisense"
  end

  def caveats
    <<~EOS
      Set up a repository:   cd <repo> && intellisense init
      Live mode for Claude:  intellisense live install
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/intellisense version")
  end
end
RUBY

cat > "$dist/intellisense.json" <<JSON
{
  "version": "$version",
  "description": "Risk tiers and evidence gates for AI-assisted development",
  "homepage": "https://github.com/soupler-oss/intellisense",
  "license": "Apache-2.0",
  "architecture": {
    "64bit": {
      "url": "$url/intellisense_${version}_windows_amd64.zip",
      "hash": "$(sha windows_amd64.zip)",
      "extract_dir": "intellisense_${version}_windows_amd64"
    },
    "arm64": {
      "url": "$url/intellisense_${version}_windows_arm64.zip",
      "hash": "$(sha windows_arm64.zip)",
      "extract_dir": "intellisense_${version}_windows_arm64"
    }
  },
  "bin": "intellisense.exe",
  "checkver": "github",
  "autoupdate": {
    "architecture": {
      "64bit": { "url": "$url/intellisense_\$version_windows_amd64.zip" },
      "arm64": { "url": "$url/intellisense_\$version_windows_arm64.zip" }
    }
  }
}
JSON
mkdir -p "$dist/winget"
cat > "$dist/winget/Soupler.Intellisense.yaml" <<YAML
# Generated by scripts/release/packaging.sh for intellisense $version.
PackageIdentifier: Soupler.Intellisense
PackageVersion: $version
DefaultLocale: en-US
ManifestType: version
ManifestVersion: 1.6.0
YAML
cat > "$dist/winget/Soupler.Intellisense.installer.yaml" <<YAML
# Generated by scripts/release/packaging.sh for intellisense $version.
PackageIdentifier: Soupler.Intellisense
PackageVersion: $version
InstallerType: zip
NestedInstallerType: portable
NestedInstallerFiles:
  - RelativeFilePath: intellisense_${version}_windows_amd64\intellisense.exe
    PortableCommandAlias: intellisense
Installers:
  - Architecture: x64
    InstallerUrl: $url/intellisense_${version}_windows_amd64.zip
    InstallerSha256: $(sha windows_amd64.zip | tr '[:lower:]' '[:upper:]')
  - Architecture: arm64
    InstallerUrl: $url/intellisense_${version}_windows_arm64.zip
    InstallerSha256: $(sha windows_arm64.zip | tr '[:lower:]' '[:upper:]')
    NestedInstallerFiles:
      - RelativeFilePath: intellisense_${version}_windows_arm64\intellisense.exe
        PortableCommandAlias: intellisense
ManifestType: installer
ManifestVersion: 1.6.0
YAML
cat > "$dist/winget/Soupler.Intellisense.locale.en-US.yaml" <<YAML
# Generated by scripts/release/packaging.sh for intellisense $version.
PackageIdentifier: Soupler.Intellisense
PackageVersion: $version
PackageLocale: en-US
Publisher: Soupler
PackageName: intellisense
License: Apache-2.0
ShortDescription: Risk tiers and evidence gates for AI-assisted development
PackageUrl: https://github.com/soupler-oss/intellisense
ManifestType: defaultLocale
ManifestVersion: 1.6.0
YAML
echo "wrote $dist/intellisense.rb, $dist/intellisense.json and $dist/winget/"
