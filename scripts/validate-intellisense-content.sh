#!/bin/bash

# intellisense Content Validation Script
# Unified validation: frontmatter, references, rule purity, stale names, governance, token budgets
# Catches breaking issues before they reach setup.sh or developers
# Fast, simple, reliable — bash only

set -e

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"

RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m'

ERRORS=()
WARNINGS=()

# Budget limits (in words)
RULES_BUDGET=1200
SKILLS_BUDGET=300
TEMPLATES_BUDGET=1800
KB_CONTEXT_BUDGET=900

add_error() {
  ERRORS+=("$1")
}

add_warning() {
  WARNINGS+=("$1")
}

print_errors() {
  echo -e "\n${RED}❌ intellisense validation failed${NC}\n"
  for err in "${ERRORS[@]}"; do
    echo -e "  ${RED}ERROR:${NC} $err"
  done
}

print_warnings() {
  if [ ${#WARNINGS[@]} -gt 0 ]; then
    echo -e "\n${YELLOW}⚠️  WARNINGS${NC}\n"
    for warn in "${WARNINGS[@]}"; do
      echo -e "  ${YELLOW}WARNING:${NC} $warn"
    done
  fi
}

# ============================================================================
# 1. FRONTMATTER VALIDATION
# ============================================================================

validate_frontmatter() {
  echo "Checking frontmatter..."
  local count=0

  # Find all markdown files that should have frontmatter
  while IFS= read -r file || [ -n "$file" ]; do
    [ -z "$file" ] && continue
    ((count++))

    # Check if file starts with ---
    if ! head -1 "$file" 2>/dev/null | grep -q "^---$"; then
      continue  # No frontmatter, skip (some templates don't require it)
    fi

    # Extract frontmatter (between first --- and second ---)
    local fm=$(sed -n '2,/^---$/p' "$file" 2>/dev/null | sed '$d')
    [ -z "$fm" ] && continue

    # Rules files must have: applies_to, phase, load_when
    if [[ "$file" == "$REPO_ROOT/rules"* ]]; then
      if ! echo "$fm" | grep -q "^applies_to:"; then
        add_error "$file: missing 'applies_to' in frontmatter"
      fi
      if ! echo "$fm" | grep -q "^phase:"; then
        add_error "$file: missing 'phase' in frontmatter"
      fi
      if ! echo "$fm" | grep -q "^load_when:"; then
        add_error "$file: missing 'load_when' in frontmatter"
      fi

      # Validate load_when value
      local lw=$(echo "$fm" | grep "^load_when:" | head -1 | sed 's/load_when: *//; s/ *$//' | tr -d '"')
      if [[ -n "$lw" ]] && ! [[ "$lw" =~ ^(always|coding|planning|testing|qa|commit)$ ]]; then
        add_error "$file: invalid load_when='$lw' (must be: always, coding, planning, testing, qa, or commit)"
      fi

      # Validate phase is array
      local ph=$(echo "$fm" | grep "^phase:" | head -1 | sed 's/phase: *//; s/ *$//')
      if [[ -n "$ph" ]] && ! [[ "$ph" =~ ^\[.*\]$ ]]; then
        add_error "$file: invalid phase format (must be array like [2, 3, 4])"
      fi

      # Validate applies_to is array
      local at=$(echo "$fm" | grep "^applies_to:" | head -1 | sed 's/applies_to: *//; s/ *$//')
      if [[ -n "$at" ]] && ! [[ "$at" =~ ^\[.*\]$ ]]; then
        add_error "$file: invalid applies_to format (must be array like [full_feature, bug_fix])"
      fi
    fi
  done < <(find "$REPO_ROOT/rules" "$REPO_ROOT/skills" "$REPO_ROOT/agents" "$REPO_ROOT/templates" \
    -name "*.md" -type f 2>/dev/null)

  echo "  Checked $count markdown files"
}

# ============================================================================
# 2. DEAD @REFERENCE DETECTION
# ============================================================================

validate_references() {
  echo "Checking @references..."
  local ref_count=0
  local missing_count=0

  while IFS= read -r source_file; do
    [ -z "$source_file" ] && continue

    # Find all @filename.md references
    while IFS= read -r ref; do
      [ -z "$ref" ] && continue
      ((ref_count++))

      # Skip special/generated references
      if [[ "$ref" == "@.intellisense-doc-health.json" ]]; then
        continue
      fi
      # Skip docs/ references (auto-generated by /document-service)
      if [[ "$ref" == "@docs/"* ]]; then
        continue
      fi
      # Skip knowledge-base/ references in service repos (auto-generated)
      if [[ "$ref" == "@knowledge-base/"* ]]; then
        continue
      fi

      # Remove @ and extract path
      local path="${ref:1}"

      # Check if file exists
      if [ ! -f "$REPO_ROOT/$path" ] && [ ! -d "$REPO_ROOT/$path" ]; then
        add_error "Missing referenced file: '$path' (referenced in $(basename "$source_file"))"
        ((missing_count++))
      fi
    done < <(grep -o '@[a-zA-Z0-9._\/-]*\.md' "$source_file" 2>/dev/null | sort -u)

  done < <(find "$REPO_ROOT/skills" "$REPO_ROOT/agents" -name "*.md" -type f 2>/dev/null)

  echo "  Found $ref_count references, $missing_count missing"
}

# ============================================================================
# 3. GENERIC RULE PURITY CHECK
# ============================================================================

validate_generic_rules() {
  echo "Checking generic rule purity..."
  local violations=0

  local forbidden=(
    "go build"
    "go test"
    "go vet"
    "go run"
    "php artisan"
    "ng build"
    "ng lint"
    "ng test"
    "ng serve"
    "pytest"
    "composer install"
    "npm install"
    "npm test"
  )

  # Only check baseline + truly generic operational files (not how-to guides)
  local check_files=(
    "$REPO_ROOT/rules/baseline/security.md"
    "$REPO_ROOT/rules/baseline/reasoning-integrity.md"
    "$REPO_ROOT/rules/operational/coding-style.md"
    "$REPO_ROOT/rules/operational/git-workflow.md"
    "$REPO_ROOT/rules/operational/patterns.md"
    "$REPO_ROOT/rules/operational/protocol-governance.md"
  )

  for rule_file in "${check_files[@]}"; do
    [ ! -f "$rule_file" ] && continue

    for cmd in "${forbidden[@]}"; do
      if grep -q "$cmd" "$rule_file" 2>/dev/null; then
        add_error "CLI command '$cmd' in $(basename "$rule_file") (belongs in language-specific rules, not generic rules)"
        ((violations++))
      fi
    done
  done

  echo "  Checked 6 generic rules, found $violations violations"
}

# ============================================================================
# 4. STALE AGENT/SERVICE NAME DETECTION
# ============================================================================

validate_stale_names() {
  echo "Checking for stale agent/service names..."
  local stale_count=0

  # Only genuinely non-existent agents (these were ghost agents before fix)
  local stale=(
    "go-backend"
    "laravel-backend"
    "frontend"
  )

  # Only check agents.md and agent spec files (where references matter)
  while IFS= read -r file; do
    [ -z "$file" ] && continue

    for name in "${stale[@]}"; do
      if grep -q "$name" "$file" 2>/dev/null; then
        add_error "Stale agent name '$name' in $(basename "$file") (agent no longer exists)"
        ((stale_count++))
      fi
    done

  done < <(echo "$REPO_ROOT/rules/operational/agents.md"; find "$REPO_ROOT/agents" -name "*.md" -type f 2>/dev/null)

  echo "  Checked agent files, found $stale_count stale references"
}

# ============================================================================
# 5. GOVERNANCE VALIDATION
# ============================================================================

validate_governance() {
  echo "Checking CLAUDE.md governance..."

  [ ! -f "$REPO_ROOT/CLAUDE.md" ] && {
    echo "  No CLAUDE.md found (skipped)"
    return 0
  }

  # Suspicious headings that should be in knowledge-base/, not CLAUDE.md
  local suspicious=(
    "Execution Mode"
    "Change Contract"
    "Mandatory Execution Phases"
    "Agent Pipeline"
    "Dev Protocol"
    "Write Protection"
    "Risk & Confidence"
    "QA Mode"
    "PR Review Mode"
  )

  # Allowed domain headings (these are fine in CLAUDE.md)
  local allowed=(
    "Architecture"
    "Domain Terms"
    "Known Gotchas"
    "API Contracts"
    "Stack"
    "Upstream Dependencies"
    "Integrations"
    "Critical Flows"
    "Data Model"
  )

  local found_issues=0
  local in_code_block=0
  local in_intellisense_block=0

  while IFS= read -r line; do
    # Track code blocks
    [[ $line =~ ^[[:space:]]*\`\`\` ]] && in_code_block=$((1 - in_code_block)) && continue
    [ $in_code_block -eq 1 ] && continue

    # Track intellisense markers
    [[ $line =~ intellisense:BEGIN ]] && in_intellisense_block=1 && continue
    [[ $line =~ intellisense:END ]] && in_intellisense_block=0 && continue
    [ $in_intellisense_block -eq 1 ] && continue

    # Check headings
    if [[ $line =~ ^##\ (.+)$ ]]; then
      local heading="${BASH_REMATCH[1]}"

      for susp in "${suspicious[@]}"; do
        if [[ "$heading" == *"$susp"* ]]; then
          local is_allowed=0
          for allow in "${allowed[@]}"; do
            [[ "$heading" == *"$allow"* ]] && is_allowed=1 && break
          done

          if [ $is_allowed -eq 0 ]; then
            add_warning "CLAUDE.md heading '$heading' looks like unmanaged protocol (should be in knowledge-base/)"
            found_issues=$((found_issues + 1))
          fi
        fi
      done
    fi
  done < "$REPO_ROOT/CLAUDE.md"

  echo "  Checked governance, found $found_issues issues"
}

# ============================================================================
# 6. TOKEN BUDGET VALIDATION
# ============================================================================

validate_token_budgets() {
  echo "Checking token budgets..."
  local found_issues=0

  # Check rule files
  if [ -d "$REPO_ROOT/rules" ]; then
    while IFS= read -r file; do
      [ ! -f "$file" ] && continue
      local word_count=$(wc -w < "$file" 2>/dev/null || echo 0)
      if [ $word_count -gt $RULES_BUDGET ]; then
        local rel_file="${file#$REPO_ROOT/}"
        add_warning "$rel_file: $word_count words (budget: $RULES_BUDGET)"
        found_issues=$((found_issues + 1))
      fi
    done < <(find "$REPO_ROOT/rules" -name "*.md" -type f 2>/dev/null)
  fi

  # Check skill files
  if [ -d "$REPO_ROOT/skills" ]; then
    while IFS= read -r file; do
      [ ! -f "$file" ] && continue
      local word_count=$(wc -w < "$file" 2>/dev/null || echo 0)
      if [ $word_count -gt $SKILLS_BUDGET ]; then
        local rel_file="${file#$REPO_ROOT/}"
        add_warning "$rel_file: $word_count words (budget: $SKILLS_BUDGET)"
        found_issues=$((found_issues + 1))
      fi
    done < <(find "$REPO_ROOT/skills" -name "*.md" -type f 2>/dev/null)
  fi

  # Check template files
  if [ -d "$REPO_ROOT/templates" ]; then
    while IFS= read -r file; do
      [ ! -f "$file" ] && continue
      local word_count=$(wc -w < "$file" 2>/dev/null || echo 0)
      if [ $word_count -gt $TEMPLATES_BUDGET ]; then
        local rel_file="${file#$REPO_ROOT/}"
        add_warning "$rel_file: $word_count words (budget: $TEMPLATES_BUDGET)"
        found_issues=$((found_issues + 1))
      fi
    done < <(find "$REPO_ROOT/templates" -type f 2>/dev/null)
  fi

  # Check project-context.md specifically
  if [ -f "$REPO_ROOT/knowledge-base/project-context.md" ]; then
    local word_count=$(wc -w < "$REPO_ROOT/knowledge-base/project-context.md" 2>/dev/null || echo 0)
    if [ $word_count -gt $KB_CONTEXT_BUDGET ]; then
      add_warning "knowledge-base/project-context.md: $word_count words (budget: $KB_CONTEXT_BUDGET)"
      found_issues=$((found_issues + 1))
    fi
  fi

  echo "  Checked budgets, found $found_issues overages"
}

# ============================================================================
# 7. BACKUP-PATH ISOLATION
# ============================================================================
# intellisense writes managed-file backups under $INTELLISENSE_BACKUPS_DIR (~/.intellisense-backups).
# These MUST NEVER enter Claude Code's auto-load surface, otherwise stale
# CLAUDE.md copies would re-enter session context. This check fails if:
#   (a) any auto-loaded markdown (rules/, skills/, agents/, templates/) carries
#       an @-import pointing into the backup dir
#   (b) any hook (whose stdout is injected into prompt context) reads files
#       under the backup dir via cat/head/tail/less/more
# Setup/restore scripts may reference the path freely — they manage it.

validate_backup_path_isolation() {
  echo "Checking backup-path isolation..."
  local violations=0

  while IFS= read -r file; do
    [ -z "$file" ] && continue
    if grep -Eq '@[^[:space:]]*\.?intellisense-backups' "$file" 2>/dev/null; then
      add_error "$file: @-import into .intellisense-backups would leak backup files into auto-load"
      ((violations++))
    fi
  done < <(find "$REPO_ROOT/rules" "$REPO_ROOT/skills" "$REPO_ROOT/agents" "$REPO_ROOT/templates" \
    -name "*.md" -type f 2>/dev/null)

  if [ -d "$REPO_ROOT/hooks" ]; then
    while IFS= read -r file; do
      [ -z "$file" ] && continue
      if grep -Eq '(cat|head|tail|less|more)[[:space:]]+[^|]*\.intellisense-backups' "$file" 2>/dev/null; then
        add_error "$file: hook reads from .intellisense-backups would inject backup content into prompt"
        ((violations++))
      fi
    done < <(find "$REPO_ROOT/hooks" -type f 2>/dev/null)
  fi

  echo "  Checked auto-load surface and hooks, found $violations isolation violations"
}

# ============================================================================
# 8. DEAD SKILL REFERENCES
# ============================================================================
# Skills are invoked as `/name` and must resolve to a skills/<name>/ directory.
# A backtick-wrapped `/name` that has no skill dir is a dead reference that
# misleads Claude at runtime (it tries to invoke a command that doesn't exist).
# Every referenced skill must exist: there is no allowlist for planned ones.
# Tokens that look like `/name` but are filesystem paths or noise, not skills.
NON_SKILL_TOKENS="tmp dev etc usr var opt bin sbin home root path null stdout stderr"
# Names deliberately cited as NONEXISTENT skills in teaching examples (e.g.
# patterns.md uses `/security-review` to teach "verify a skill exists first").
INTENTIONAL_NONEXISTENT_SKILLS="security-review"

validate_skill_references() {
  echo "Checking skill references..."
  local valid_set=" "
  local dir
  for dir in "$REPO_ROOT"/skills/*/; do
    [ -d "$dir" ] || continue
    valid_set+="$(basename "$dir") "
  done
  valid_set+="$NON_SKILL_TOKENS $INTENTIONAL_NONEXISTENT_SKILLS "

  local checked=0 dead=0 name
  while IFS= read -r file; do
    [ -z "$file" ] && continue
    # backtick-wrapped invocations: `/name` or `/name arg` — extract the name
    while IFS= read -r name; do
      [ -z "$name" ] && continue
      ((checked++))
      if [[ "$valid_set" != *" $name "* ]]; then
        add_error "Dead skill reference '/$name' in $(basename "$file") — no skills/$name/ directory (add the skill or fix the name)"
        ((dead++))
      fi
    # A skill invocation is `/name` closed by a backtick (`/verify`) or a space
    # before args (`/shared-table-impact [t]`). An HTTP path like `/api/foo` has
    # a `/` after the name, so requiring the trailing backtick-or-space excludes
    # endpoint paths from being mistaken for skills.
    done < <(grep -oE '`/[a-z][a-z0-9-]{2,}[`[:space:]]' "$file" 2>/dev/null | sed -e 's:`/::' -e 's:[`[:space:]]$::' | sort -u)
    # Scope: skills/ and rules/operational/ — where skills are invoked as
    # workflow steps. rules/language-specific/ documents HTTP endpoints and code
    # patterns (e.g. Spring Actuator `/env`), not skills, so it is excluded.
  done < <(find "$REPO_ROOT/skills" "$REPO_ROOT/rules/operational" -name "*.md" -type f 2>/dev/null)

  echo "  Checked $checked backtick-wrapped skill refs, $dead dead"
}

# ============================================================================
# 9. FORBIDDEN BYPASS INSTRUCTIONS
# ============================================================================
# hooks/pre-push implements NO env-var bypass ("not hidden env variables").
# Any doc that instructs `INTELLISENSE_BYPASS=...` teaches a nonexistent, forbidden
# bypass. Prose noting that no such variable exists is fine (no `=` form).
# Scope is the WHOLE repo (not just the auto-load surface) — a phantom-bypass
# instruction misleads in a root guide or docs/ page too.

validate_no_bypass_instructions() {
  echo "Checking for forbidden bypass instructions..."
  local hits=0
  while IFS= read -r file; do
    [ -z "$file" ] && continue
    if grep -nE 'INTELLISENSE_BYPASS[A-Z_]*=' "$file" >/dev/null 2>&1; then
      add_error "$file: documents an 'INTELLISENSE_BYPASS=' instruction — pre-push implements no env-var bypass; use commit/PR approval or .intellisense/exception-allowlist.yaml"
      ((hits++))
    fi
  done < <(find "$REPO_ROOT" -name "*.md" -type f \
    -not -path "*/.git/*" -not -path "*/.beads/*" \
    -not -path "*/.intellisense/*" -not -path "*/node_modules/*" 2>/dev/null)

  echo "  Checked repo-wide, found $hits forbidden bypass instruction(s)"
}

# ============================================================================
# 10. STALE "CHUNK B" FRAMING
# ============================================================================
# "Chunk B" was an internal rollout-phase label for protocols that have since
# shipped (independent-review in agents.md, pattern-lifecycle in
# protocol-governance.md). Any remaining "Chunk B" reference in rules/ or skills/
# tells the reader to treat shipped content as future/advisory — stale framing.

validate_no_chunk_b() {
  echo "Checking for stale 'Chunk B' framing..."
  local hits=0
  while IFS= read -r file; do
    [ -z "$file" ] && continue
    if grep -nE 'Chunk[ -]B' "$file" >/dev/null 2>&1; then
      add_error "$file: stale 'Chunk B' rollout-phase reference — those protocols have shipped (agents.md / protocol-governance.md); reword without the Chunk-B label"
      ((hits++))
    fi
  done < <(find "$REPO_ROOT/rules" "$REPO_ROOT/skills" -name "*.md" -type f 2>/dev/null)

  echo "  Checked rules/ + skills/, found $hits stale Chunk-B reference(s)"
}

# ============================================================================
# 11. GENERICNESS REGRESSION GUARD
# ============================================================================
# intellisense was genericized from a single company's internal deployment. A banned
# literal reappearing here means org-specific data crept back into the
# portable framework. rules/organization/ is the one place it's expected —
# that's the documented overlay for an adopting org's own proprietary rules.

validate_no_org_specific_literals() {
  echo "Checking for org-specific literals outside rules/organization/..."
  local hits=0
  # "dolt" is deliberately NOT banned: it's the (public, third-party) storage
  # engine Beads uses internally, not organization-specific data. Beads/Dolt
  # are kept as an optional reference tracker implementation — see
  # task-tracking-beads.md — so mentioning them by name is documentation,
  # not a leak. Ban actual business/vendor specifics only.
  # Organisation-specific terms to ban, one regex per line, in
  # .intellisense/banned-terms.txt (optional; keeps names out of this file too).
  local banned=()
  if [ -f "$REPO_ROOT/.intellisense/banned-terms.txt" ]; then
    while IFS= read -r t; do [ -n "$t" ] && banned+=("$t"); done < "$REPO_ROOT/.intellisense/banned-terms.txt"
  fi
  while IFS= read -r file; do
    [ -z "$file" ] && continue
    case "$file" in
      "$REPO_ROOT"/rules/organization/*) continue ;;
      "$SCRIPT_DIR"/validate-intellisense-content.sh) continue ;;  # this file documents the banned words themselves
    esac
    for pattern in "${banned[@]}"; do
      if grep -inE "$pattern" "$file" >/dev/null 2>&1; then
        add_error "$file: org-specific literal matching '$pattern' outside rules/organization/ (framework should stay generic)"
        ((hits++))
      fi
    done
  done < <(find "$REPO_ROOT" -type f \( -name "*.md" -o -name "*.sh" -o -name "*.json" -o -name "*.py" -o -name "*.yml" \) \
    -not -path "*/.git/*" -not -path "*/.beads/*" -not -path "*/.intellisense/*" -not -path "*/node_modules/*" 2>/dev/null)

  echo "  Checked repo-wide (excl. rules/organization/), found $hits org-specific literal(s)"
}

# §6a — positive-manifest gate-coverage check: assert safety invariants are
# PRESENT in the always-loaded development-workflow.md (delegates to the
# standalone, unit-tested scripts/check-workflow-invariants.sh).
validate_workflow_invariants() {
  echo "Checking always-loaded workflow invariants (§6a manifest)..."
  local wf="$REPO_ROOT/rules/operational/development-workflow.md"
  local checker="$SCRIPT_DIR/check-workflow-invariants.sh"
  [ -f "$wf" ] || { echo "  development-workflow.md not found — skipped"; return 0; }
  if [ ! -x "$checker" ]; then
    add_error "check-workflow-invariants.sh missing or not executable: $checker"
    return 0
  fi
  local out
  if ! out=$(bash "$checker" "$wf" 2>&1); then
    while IFS= read -r line; do
      [ -n "$line" ] && add_error "workflow-invariant: $line"
    done <<< "$out"
  else
    echo "  $out"
  fi
}

# ============================================================================
# MAIN
# ============================================================================

main() {
  echo -e "${YELLOW}Starting intellisense validation...${NC}\n"

  validate_frontmatter
  validate_references
  validate_generic_rules
  validate_stale_names
  validate_governance
  validate_token_budgets
  validate_backup_path_isolation
  validate_skill_references
  validate_no_bypass_instructions
  validate_no_chunk_b
  validate_no_org_specific_literals
  validate_workflow_invariants

  echo ""

  if [ ${#ERRORS[@]} -eq 0 ]; then
    print_warnings
    echo -e "${GREEN}✅ intellisense validation passed${NC}"
    return 0
  else
    print_errors
    print_warnings
    return 1
  fi
}

main "$@"
